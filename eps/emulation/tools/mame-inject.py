#!/usr/bin/env python3
"""Prepare MAME memory-injection boot for a (patched) EPS OS EFE.

MAME's EPS floppy emulation stalls in the boot ROM's disk-detect retry loop,
so we bypass it: a Lua autoboot script waits ~2s (ROM init + RAM clear done,
ROM spinning in the retry loop), injects every scatter-load segment the ROM
loader would have produced, clears the boot error flag, and jumps to C0BEC0
(the post-load path: display init -> kernel start C0729C).

Injects and verifies low RAM through the unconditional $FF0000 alias. The
EPS maps low instruction fetches to ROM in supervisor mode; using ordinary
low-address Lua writes can silently discard data depending on CPU function
code. Diagnostic RAM reads likewise use the unconditional alias.

Usage: mame-inject.py <os.efe> [outdir]
Then:  mame eps -autoboot_script <outdir>/inject.lua
"""
import sys
from pathlib import Path

efe = Path(sys.argv[1]).read_bytes()
osb = efe[512:]
out = Path(sys.argv[2] if len(sys.argv) > 2 else "mame_inject")
out.mkdir(exist_ok=True)

segs = [  # (file, ram_addr, file_off, size)
    ("seg_vec.bin",  0x000000, 0x00000, 0x0200),
    ("seg_cfg.bin",  0x000200, 0x14C00, 0x0028),
    ("seg_low1.bin", 0x001600, 0x14000, 0x0C00),
    ("seg_low2.bin", 0x002200, 0x00200, 0x5E00),
    ("seg_hi.bin",   0xFF8000, 0x06000, 0x8000),
]
lua_segs = []
for fname, ram, off, size in segs:
    (out / fname).write_bytes(osb[off:off + size])
    lua_segs.append(f'  {{ path = "{(out / fname).resolve()}", addr = 0x{ram:x} }},')

lua = """-- EPS OS memory-injection boot (generated by mame-inject.py)
_G.eps_inject = { frames = 0, done = false }   -- global: keep GC away
local segs = {
%s
}
_G.eps_inject.sub = emu.add_machine_frame_notifier(function()
  local st = _G.eps_inject
  st.frames = st.frames + 1
  local cpu = manager.machine.devices[":maincpu"]
  if not st.done and st.frames >= 120 then
    st.done = true
    local mem = cpu.spaces["program"]
    for _, s in ipairs(segs) do
      local f = assert(io.open(s.path, "rb"))
      local d = f:read("*a")
      f:close()
      for i = 1, #d do
        -- EPS low addresses select ROM on supervisor instruction fetches.
        -- Lua inherits the CPU's current function code, so writes through
        -- lower_w can silently be ignored. Use the unconditional RAM alias.
        local physical = s.addr < 0x8000 and (0xff0000 + s.addr) or s.addr
        mem:write_u8(physical + i - 1, string.byte(d, i))
      end
      for i = 1, #d do
        local physical = s.addr < 0x8000 and (0xff0000 + s.addr) or s.addr
        assert(mem:read_u8(physical + i - 1) == string.byte(d, i), "RAM injection mismatch")
      end
    end
    mem:write_u8(0xff02c8, 0)   -- boot error flag = OK (physical RAM alias)
    cpu.state["SR"].value = 0x2700
    cpu.state["SP"].value = 0x1548
    local ok, err = pcall(function() cpu.state["PC"].value = 0xc0bec0 end)
    print("EPS OS injected; PC write ok=" .. tostring(ok) .. " " .. tostring(err))
  end
  if st.done and st.frames %% 300 == 0 and st.frames <= 1800 then
    local mem = cpu.spaces["program"]
    print(string.format("frame %%d PC=%%06x panic=%%02x kmode=%%02x",
      st.frames, cpu.state["PC"].value, mem:read_u16(0xff0138), mem:read_u8(0xff02c8)))
    print(string.format("alive=%%04x idle=%%04x taskPC=%%08x taskUSP=%%04x",
      mem:read_u16(0xff7f00), mem:read_u16(0xff7f02),
      mem:read_u32(0xffcb98), mem:read_u16(0xffcba0)))
  end
end)
""" % "\n".join(lua_segs)
(out / "inject.lua").write_text(lua)
print(f"wrote {out}/inject.lua + {len(segs)} segment files")
